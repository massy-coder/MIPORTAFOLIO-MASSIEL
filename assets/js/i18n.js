  var TYPED_EN = ['Massiel Núñez', 'Turning Ideas Into Impact.', 'Creative Mind', 'Aspiring Digital Communicator', 'Lifelong Learner'];
  var TYPED_ES = ["Massiel Núñez", "Convirtiendo ideas en impacto.", "Mente creativa", "Aspirante a comunicadora digital", "Aprendiz de por vida"];

  var root = document.documentElement;
  var ATTRS = ['alt', 'placeholder', 'aria-label', 'title'];
  var textOrig = new WeakMap();
  var attrOrig = new WeakMap();
  var lang = root.getAttribute('lang') === 'es' ? 'es' : 'en';
  var observer = null, busy = false;

  function norm(s) { return s.replace(/\s+/g, ' ').trim(); }

  function t(key) { return (lang === 'es' && ES[key]) ? ES[key] : key; }

  function walkText() {
    var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
    var n;
    while ((n = w.nextNode())) {
      var p = n.parentNode && n.parentNode.nodeName;
      if (p === 'SCRIPT' || p === 'STYLE' || p === 'NOSCRIPT') continue;
      if (n.parentNode && n.parentNode.closest && n.parentNode.closest('.type, .typed-cursor')) continue;
      var orig = textOrig.get(n);
      if (orig === undefined) {
        var k = norm(n.nodeValue);
        orig = (k && ES[k]) ? n.nodeValue : null;
        textOrig.set(n, orig);
      }
      if (orig === null) continue;
      if (lang === 'es') {
        var lead = orig.match(/^\s*/)[0], trail = orig.match(/\s*$/)[0];
        n.nodeValue = lead + ES[norm(orig)] + trail;
      } else {
        n.nodeValue = orig;
      }
    }
  }

  function walkAttrs() {
    var els = document.querySelectorAll('[alt],[placeholder],[aria-label],[title]');
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      if (el.hasAttribute('data-i18n-skip')) continue;
      var store = attrOrig.get(el);
      if (!store) { store = {}; attrOrig.set(el, store); }
      for (var j = 0; j < ATTRS.length; j++) {
        var a = ATTRS[j];
        if (!el.hasAttribute(a)) continue;
        if (store[a] === undefined) {
          var v = el.getAttribute(a).trim();
          store[a] = ES[v] ? v : null;
        }
        if (store[a] === null) continue;
        el.setAttribute(a, lang === 'es' ? ES[store[a]] : store[a]);
      }
    }
    var meta = document.querySelector('meta[name="description"]');
    if (meta) {
      if (!meta.__en) meta.__en = meta.getAttribute('content');
      meta.setAttribute('content', lang === 'es' && ES[meta.__en] ? ES[meta.__en] : meta.__en);
    }
  }

  function restartTyped() {
    if (typeof Typed === 'undefined' || !document.querySelector('.type')) return;
    try { if (window.typed && window.typed.destroy) window.typed.destroy(); } catch (e) {}
    var el = document.querySelector('.type'); if (el) el.textContent = '';
    window.typed = new Typed('.type', { strings: lang === 'es' ? TYPED_ES : TYPED_EN, typeSpeed: 80, backSpeed: 80, loop: true });
  }

  function paintButtons() {
    var bs = document.querySelectorAll('#lang-toggle button');
    for (var i = 0; i < bs.length; i++) bs[i].setAttribute('aria-pressed', bs[i].getAttribute('data-lang') === lang ? 'true' : 'false');
  }

  function apply() {
    busy = true;
    if (observer) observer.disconnect();
    root.setAttribute('lang', lang);
    walkText(); walkAttrs(); paintButtons();
    startObserver();
    busy = false;
  }

  function startObserver() {
    if (!window.MutationObserver || !document.body) return;
    if (!observer) {
      var timer = null;
      observer = new MutationObserver(function (muts) {
        if (busy || lang !== 'es') return;
        var real = false;
        for (var i = 0; i < muts.length; i++) {
          var tg = muts[i].target;
          var el = tg.nodeType === 1 ? tg : tg.parentNode;
          if (el && el.closest && el.closest('.type, .typed-cursor')) continue;
          real = true; break;
        }
        if (!real) return;
        clearTimeout(timer);
        timer = setTimeout(apply, 120);
      });
    }
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  function setLang(l, save) {
    lang = l === 'es' ? 'es' : 'en';
    if (save) { try { localStorage.setItem('lang', lang); } catch (e) {} }
    apply();
    restartTyped();
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  window.siteI18n = { t: t, set: function (l) { setLang(l, true); }, get: function () { return lang; } };

  var bs = document.querySelectorAll('#lang-toggle button');
  for (var i = 0; i < bs.length; i++) {
    bs[i].addEventListener('click', function () { setLang(this.getAttribute('data-lang'), true); });
  }

  apply();
  if (lang === 'es') restartTyped();
  window.addEventListener('load', function () {
    apply();
    if (lang === 'es') restartTyped();
    setTimeout(apply, 900);
  });
